// People-Skills junction table (many-to-many)
export const peopleSkills = sqliteTable('peopleSkills', {
  id: text('id').primaryKey().$defaultFn(() => createId()),
  personId: text('personId').notNull().references(() => people.id, { onDelete: 'cascade' }),
  skillId: text('skillId').notNull().references(() => skills.id, { onDelete: 'cascade' }),
  order: integer('order').default(0).notNull(),
  createdAt: integer('createdAt', { mode: 'timestamp' }).$defaultFn(() => new Date()).notNull(),
});

// People relations
export const personCategoriesRelations = relations(personCategories, ({ many }) => ({
  people: many(people)
}));

export const personTitlesRelations = relations(personTitles, ({ many }) => ({
  people: many(people)
}));

export const skillsRelations = relations(skills, ({ many }) => ({
  peopleSkills: many(peopleSkills)
}));

export const peopleRelations = relations(people, ({ one, many }) => ({
  category: one(personCategories, {
    fields: [people.categoryId],
    references: [personCategories.id]
  }),
  title: one(personTitles, {
    fields: [people.titleId],
    references: [personTitles.id]
  }),
  skills: many(peopleSkills)
}));

export const peopleSkillsRelations = relations(peopleSkills, ({ one }) => ({
  person: one(people, {
    fields: [peopleSkills.personId],
    references: [people.id]
  }),
  skill: one(skills, {
    fields: [peopleSkills.skillId],
    references: [skills.id]
  })
}));
