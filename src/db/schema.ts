// Purchases table
export const purchases = sqliteTable('purchases', {
  id: text('id').primaryKey().$defaultFn(() => createId()),
  userId: text('userId').references(() => users.id, { onDelete: 'set null' }),
  productId: text('productId').notNull().references(() => products.id),
  purchaseCode: text('purchaseCode').notNull().unique(), // Unique code for registration
  email: text('email').notNull(), // Email where purchase code was sent

  // Payment provider info (generic for multi-provider support)
  paymentProvider: text('paymentProvider'), // 'mercadopago', 'stripe', 'paypal', etc.
  externalPaymentId: text('externalPaymentId').unique(), // Provider's payment ID
  externalOrderId: text('externalOrderId'), // Provider's order ID
  providerStatus: text('providerStatus'), // Provider-specific status
  providerStatusDetail: text('providerStatusDetail'), // Provider-specific status detail
  checkoutUrl: text('checkoutUrl'), // Checkout URL generated by provider

  amount: integer('amount').notNull(), // Amount paid in cents
  currency: text('currency').default('USD').notNull(),

  // Status tracking
  status: text('status', {
    enum: ['initialized', 'pending', 'completed', 'refunded', 'failed']
  }).default('initialized').notNull(),

  // Discount fields
  couponId: text('couponId'),
  offerId: text('offerId'),
  discountSource: text('discountSource', { enum: ['coupon', 'offer'] }),
  discountAmount: integer('discountAmount').default(0).notNull(), // Discount in cents
  originalAmount: integer('originalAmount'), // Original price before discount

  // Registration tracking
  usedForRegistration: integer('usedForRegistration', { mode: 'boolean' }).default(false).notNull(),
  registrationUsedAt: integer('registrationUsedAt', { mode: 'timestamp' }),

  createdAt: integer('createdAt', { mode: 'timestamp' }).$defaultFn(() => new Date()).notNull(),
  updatedAt: integer('updatedAt', { mode: 'timestamp' }).$defaultFn(() => new Date()).notNull(),
});

